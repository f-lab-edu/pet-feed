CREATE TABLE follows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_key VARCHAR(255) NOT NULL,
    following_key VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_follow_pair UNIQUE (follower_key, following_key),
    CONSTRAINT ck_follow_distinct CHECK (follower_key <> following_key)
);
CREATE INDEX idx_follow_follower ON follows (follower_key, id);
CREATE INDEX idx_follow_following ON follows (following_key, id);
